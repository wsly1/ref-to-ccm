class StarCcmRunner:
    def __init__(self, config: ToolConfig) -> None:
        self.config = config

    def run(self, macro_file: Path) -> Path:
        if self.config.starccm_exe is None:
            raise ValueError("starccm.starccm_exe is required unless --no-run-star is used.")
        if not self.config.starccm_exe.exists():
            raise FileNotFoundError(f"STAR-CCM+ executable does not exist: {self.config.starccm_exe}")
        if not self.config.sim_file.exists():
            raise FileNotFoundError(f"STAR-CCM+ sim file does not exist: {self.config.sim_file}")

        command = [
            str(self.config.starccm_exe),
            "-batch",
            str(macro_file),
            str(self.config.sim_file),
        ]
        log_file = self.config.output_directory / "starccm_run.log"
        with log_file.open("w", encoding="utf-8", errors="replace") as handle:
            handle.write("Command:\n")
            handle.write(" ".join(command))
            handle.write("\n\nOutput:\n")
            try:
                completed = subprocess.run(
                    command,
                    stdout=handle,
                    stderr=subprocess.STDOUT,
                    text=True,
                    check=False,
                    timeout=STARCCM_RUN_TIMEOUT_SECONDS,
                )
            except subprocess.TimeoutExpired as exc:
                handle.write(f"\nSTAR-CCM+ run timed out after {STARCCM_RUN_TIMEOUT_SECONDS} seconds.\n")
                raise TimeoutError(
                    f"STAR-CCM+ 运行超时（超过 {STARCCM_RUN_TIMEOUT_SECONDS} 秒）。"
                    f"日志: {log_file.resolve()}"
                ) from exc
        if completed.returncode != 0:
            raise RuntimeError(f"STAR-CCM+ run failed with exit code {completed.returncode}. Log: {log_file.resolve()}")
        return log_file.resolve()


