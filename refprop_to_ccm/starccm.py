def _fit_property_polynomials(path: Path, degree: int) -> PropertyPolynomials:
    rows = _read_property_rows(path)
    if not rows:
        raise ValueError(f"No property rows found in {path}")

    temperatures = np.array([row["temperature"] for row in rows], dtype=float)
    effective_degree = min(max(0, int(degree)), max(len(temperatures) - 1, 0))

    def fit(column: str) -> tuple[float, ...]:
        values = np.array([row[column] for row in rows], dtype=float)
        if not np.all(np.isfinite(values)):
            raise ValueError(f"Non-finite values found in {path} column {PROPERTY_CSV_COLUMNS[column]}")
        coefficients = np.polynomial.polynomial.polyfit(temperatures, values, effective_degree)
        return tuple(float(value) for value in coefficients)

    return PropertyPolynomials(
        temperature_min_c=float(np.min(temperatures)),
        temperature_max_c=float(np.max(temperatures)),
        density=fit("density"),
        specific_heat=fit("specific_heat"),
        thermal_conductivity=fit("thermal_conductivity"),
        dynamic_viscosity=fit("dynamic_viscosity"),
        enthalpy=fit("enthalpy"),
    )


def _read_property_rows(path: Path) -> list[dict[str, float]]:
    rows: list[dict[str, float]] = []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        missing = [column for column in PROPERTY_CSV_COLUMNS.values() if column not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"Missing required REFPROP CSV columns in {path}: {', '.join(missing)}")
        for row in reader:
            parsed = {
                key: float(row[column_name])
                for key, column_name in PROPERTY_CSV_COLUMNS.items()
            }
            if not all(np.isfinite(value) for value in parsed.values()):
                raise ValueError(f"Non-finite property row found in {path}")
            rows.append(parsed)
    return rows


